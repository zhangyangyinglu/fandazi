/**
 * 同义词归一化:将用户可能输入的别名映射到菜库标准名。
 */
export function normalizeIngredientName(name: string): string {
  return SYNONYMS[name] ?? name
}

/**
 * 获取食材的子分类。
 */
export function getSubCategory(name: string): IngredientSubCategory {
  const normalized = normalizeIngredientName(name)
  return SUBCATEGORY_MAP[normalized] ?? '未知'
}

/**
 * 在库存中查找可替代指定食材的其他库存项。
 * @param targetName 菜谱需要的食材名
 * @param pantryItems 当前库存
 * @returns 可替代的库存项数组(不含同名匹配)
 */
export function findSubstitutes(
  targetName: string,
  pantryItems: PantryItem[],
): PantryItem[] {
  const normalizedTarget = normalizeIngredientName(targetName)
  const targetSub = getSubCategory(targetName)

  // 未知子类或单独类别(不互替)
  if (targetSub === '未知') return []
  if (targetSub === '瓜类' || targetSub === '茄果' || targetSub === '花茎' ||
      targetSub === '豆类' || targetSub === '笋类' || targetSub === '根茎' ||
      targetSub === '鲜肉羊' || targetSub === '禽肉' || targetSub === '海鲜鱼' ||
      targetSub === '海鲜其他' || targetSub === '其他荤') {
    // 这些子类内部差异太大,不做自动互替
    // 但仍然检查同义词
    return pantryItems.filter((item) => {
      const itemNormalized = normalizeIngredientName(item.ingredientName)
      return itemNormalized === normalizedTarget && item.ingredientName !== targetName
    })
  }

  // 可互替的子类:同子类内,排除同名
  return pantryItems.filter((item) => {
    const itemNormalized = normalizeIngredientName(item.ingredientName)
    const itemSub = getSubCategory(item.ingredientName)
    return itemSub === targetSub && itemNormalized !== normalizedTarget
  })
}

/**
 * 检查两个食材名是否等价(同义词或同名)。
 */
export function isIngredientEquivalent(name1: string, name2: string): boolean {
  return normalizeIngredientName(name1) === normalizeIngredientName(name2)
}

/**
 * 获取食材的 IngredientGroup(从子分类反推)。
 */
export function getGroupFromSubCategory(sub: IngredientSubCategory): IngredientGroup {
  switch (sub) {
    case '绿叶菜': case '茄果': case '瓜类': case '花茎':
    case '豆类': case '笋类': case '根茎': case '菌菇':
      return '蔬菜'
    case '豆制品': case '蛋类': case '鲜肉猪': case '鲜肉牛':
    case '鲜肉羊': case '禽肉': case '海鲜鱼': case '海鲜虾':
    case '海鲜其他': case '其他荤':
      return '肉蛋'
    case '调味':
      return '调味'
    case '干货':
      return '干货'
    case '主食':
      return '主食'
    default:
      return '蔬菜'
  }
}
