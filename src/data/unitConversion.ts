/**
 * 将食材的某个单位数量转换为克。
 * @returns 克数;无法换算时返回 null
 */
export function convertToGrams(
  ingredientName: string,
  value: number,
  unit: string,
): number | null {
  // 1. 食材特指表
  const table = INGREDIENT_UNIT_GRAMS[ingredientName]
  if (table && table[unit] !== undefined) {
    return value * table[unit]
  }
  // 2. 通用表
  if (GENERIC_UNIT_GRAMS[unit] !== undefined) {
    return value * GENERIC_UNIT_GRAMS[unit]
  }
  // 3. 无法换算
  return null
}

/**
 * 尝试将两个不同单位的食材数量统一到克并比较。
 * @returns { haveGrams, needGrams } 或 null（无法换算时）
 */
export function compareAmounts(
  ingredientName: string,
  haveValue: number,
  haveUnit: string,
  needValue: number,
  needUnit: string,
): { haveGrams: number; needGrams: number } | null {
  // 同单位直接比
  if (haveUnit === needUnit) {
    return { haveGrams: haveValue, needGrams: needValue }
  }
  // 换算到克
  const haveGrams = convertToGrams(ingredientName, haveValue, haveUnit)
  const needGrams = convertToGrams(ingredientName, needValue, needUnit)
  if (haveGrams === null || needGrams === null) return null
  return { haveGrams, needGrams }
}
